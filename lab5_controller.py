def convert_paths_to_waypoints(all_paths, density_level=0):
    """
    Converts path segments from map coordinates to world coordinates and returns waypoints.
    
    :param all_paths: List of path segments, where each segment is a list of (x,y) map coordinates
    :param density_level: 0 for sparse waypoints, 1 for dense waypoints
    :return: List of waypoints in world coordinates
    """
    all_waypoints = []
    
    if all_paths:

        
        for segment_idx, path in enumerate(all_paths):
            
            # Determine spacing based on path length and density level
            if density_level == 0:  # Sparse waypoints
                first_spacing = 30
                middle_spacing = 20
                last_spacing = 10
            else:  # Dense waypoints
                first_spacing = 15
                middle_spacing = 10
                last_spacing = 5
            
            # Determine portion sizes
            first_portion = min(len(path) // 3, 100)
            second_portion = min(2 * len(path) // 3, 200)
            
            segment_waypoints = []
            
            # Big spacing for first portion
            if first_portion > first_spacing:
                for i in range(0, first_portion, first_spacing):
                    point = path[i]
                    wx = -((360 - point[0]) / 30.0)
                    wy = -((point[1]) / 30.0)
                    segment_waypoints.append((wx, wy))
            
            # Medium spacing for middle portion
            if second_portion > first_portion:
                for i in range(first_portion, second_portion, middle_spacing):
                    point = path[i]
                    wx = -((360 - point[0]) / 30.0)
                    wy = -((point[1]) / 30.0)
                    segment_waypoints.append((wx, wy))
            
            # Close spacing for last portion
            for i in range(second_portion, len(path), last_spacing):
                point = path[i]
                wx = -((360 - point[0]) / 30.0)
                wy = -((point[1]) / 30.0)
                segment_waypoints.append((wx, wy))
            
            # Always include the end of each segment
            last_point = path[-1]
            wx = -((360 - last_point[0]) / 30.0)
            wy = -((last_point[1]) / 30.0)
            end_already_added = False
            for i, wp in enumerate(segment_waypoints):
                if abs(wp[0] - wx) < 0.1 and abs(wp[1] - wy) < 0.1:
                    end_already_added = True
                    break
            if not end_already_added:
                segment_waypoints.append((wx, wy))
            
            # Add this segment's waypoints to the full list
            # Skip the first waypoint of each segment after the first to avoid duplicates
            if segment_idx > 0 and segment_waypoints:
                all_waypoints.extend(segment_waypoints[1:])
            else:
                all_waypoints.extend(segment_waypoints)
        
        # Remove the starting point as it's the robot's current position
        if all_waypoints:
            all_waypoints.pop(0)
            
    return all_waypoints
