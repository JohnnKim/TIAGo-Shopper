# This used opencv's findContours function to find the contours of the objects in the image.
# HW3's method is, frankly, worse, as opencv's method is really good. 
# This function was used to annotate the images for the YOLO training data.
def detect_objects_by_color(bgr_image, target_color, min_contour_area=50):
    """
    Detects objects of a specific color in a BGR image using HSV thresholding.

    Args:
        bgr_image: The input image in BGR format (NumPy array).
        target_color (str): The name of the color to detect (e.g., 'red', 'yellow').
                              Must be a key in COLOR_RANGES_HSV.
        min_contour_area (int): The minimum area for a contour to be considered an object.

    Returns:
        tuple: A tuple containing:
            - list[DetectedObject]: A list of detected objects.
            - np.ndarray: The binary mask used for detection. Returns None if color invalid.
    """
    if target_color not in COLOR_RANGES_HSV:
        print(f"Error: Color '{target_color}' not defined in COLOR_RANGES_HSV.")
        return [], None

    # Convert BGR to HSV
    hsv_image = cv2.cvtColor(bgr_image, cv2.COLOR_BGR2HSV)

    # Get ranges for the target color
    ranges = COLOR_RANGES_HSV[target_color]

    # Create mask(s)
    mask1 = cv2.inRange(hsv_image, ranges['lower1'], ranges['upper1'])
    if 'lower2' in ranges: #only use the second range if it exists
        mask2 = cv2.inRange(hsv_image, ranges['lower2'], ranges['upper2'])
        full_mask = mask1 + mask2
    else:
        full_mask = mask1

    # Find contours
    contours, _ = cv2.findContours(full_mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)

    detected_objects = []
    for contour in contours:
        area = cv2.contourArea(contour)
        if area > min_contour_area: #filter out small objects
            x, y, w, h = cv2.boundingRect(contour) #get the bounding box of the object
            center_x = x + w // 2
            center_y = y + h // 2
            obj = DetectedObject(
                x=x, y=y, w=w, h=h,
                cx=center_x, cy=center_y,
                area=area, color=target_color, confidence=1
            ) #create a detected object instance
            detected_objects.append(obj)

    return detected_objects, full_mask

# Mostly written by me (Mitch), but I used Gemini 2.5 pro to help me write the comments.
def draw_detected_objects(detected_objects, original_image):
    """Draws bounding boxes and info for detected objects on the image."""
    # copy of the original image
    drawing_image = original_image.copy()
    color_map = {
        'red': (0, 0, 255),      # BGR Red
        'yellow': (0, 255, 255), # BGR Yellow
        'blue': (255, 0, 0),     # BGR Blue
        'bright_green': (0, 255, 0), # BGR Green
        'white': (255, 255, 255) # BGR White
    }
    default_color = (0, 0, 0) # Black for unknown colors

    for obj in detected_objects:
        draw_x = int(obj.x)
        draw_y = int(obj.y)
        draw_w = int(obj.w)
        draw_h = int(obj.h)
        draw_cx = int(obj.cx)
        draw_cy = int(obj.cy)

        draw_color = color_map.get(obj.color, default_color)
        # Draw rectangle
        cv2.rectangle(drawing_image, (draw_x, draw_y), (draw_x + draw_w, draw_y + draw_h), draw_color, 2)

        # Put text for center pixel coordinates and confidence
        info_text1 = f"({draw_cx},{draw_cy},{obj.confidence:.2f})"
        cv2.putText(drawing_image, info_text1, (draw_x, draw_y - 15), cv2.FONT_HERSHEY_SIMPLEX, 0.3, draw_color, 1)

    return drawing_image


