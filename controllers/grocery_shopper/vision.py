class DetectedObject: #fun little class I made to keep track of the detected objects.
    """Represents a detected object with its properties."""
    def __init__(self, x, y, w, h, cx, cy, area, color, confidence=1):
        self.x = x #top-left x coord
        self.y = y #top-left y coord
        self.w = w #width
        self.h = h #height
        self.cx = cx #center x coord
        self.cy = cy #center y coord
        self.area = area #area of the object, used to filter out small objects in color detection.
        self.color = color
        self.confidence = confidence #this defaults to 1 if using color detection.


